// Screenshots of the main screens (no assertions). usage: node tests/look.cjs <url> <outdir>
const { chromium } = require('playwright');
const fs = require('fs');
const url = process.argv[2] || 'http://127.0.0.1:8099/';
const out = process.argv[3] || 'build/look';
fs.mkdirSync(out, { recursive: true });
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const vp = (process.env.VP || '412x892').split('x').map(Number);
  const ctx = await b.newContext({ viewport: { width: vp[0], height: vp[1] }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const p = await ctx.newPage();
  const errs = [];
  p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.text()); });
  p.on('pageerror', e => errs.push(e.message));
  const t0 = Date.now();
  await p.goto(url + '?reset&lowpower');
  await p.waitForFunction(() => window.__game && window.__game.state.mode === 'attract', null, { timeout: 180000 });
  console.log('loaded in', Date.now() - t0, 'ms');
  await sleep(800);
  await p.screenshot({ path: `${out}/1_start.png` });
  await p.tap('[data-level="easy"]');
  await sleep(600);
  await p.tap('#bHelpGo');
  await sleep(900);
  await p.screenshot({ path: `${out}/2_play.png` });
  await p.evaluate(() => { const s = window.__game.state; s.order.slice(0, 40).forEach(c => window.__game.place(c, false)); });
  await sleep(600);
  await p.screenshot({ path: `${out}/3_partial.png` });
  await p.evaluate(() => { const s = window.__game.state; s.order.forEach(c => { if (!s.placed.includes(c)) window.__game.place(c, false); }); });
  await sleep(2500);
  await p.evaluate(() => { const v = window.__game.view; v.animateTo({ x: 10, z: -25, dist: v.fitDist * 0.3, tilt: 0.85, yaw: 0.4 }, 10); });
  await sleep(700);
  await p.screenshot({ path: `${out}/4_close.png` });
  const info = await p.evaluate(() => ({ calls: window.__game.view.renderer.info.render.calls, tris: window.__game.view.renderer.info.render.triangles }));
  console.log('render', JSON.stringify(info));
  console.log('errors:', errs.length ? errs.join('\n') : 'none');
  await b.close();
})();
