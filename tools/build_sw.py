"""Writes sw.js: an offline cache of every file the game needs, versioned by content hash.
Run from the repo root after any change: python3 tools/build_sw.py"""
import hashlib, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INCLUDE = ["index.html", "manifest.webmanifest", "css", "js", "data", "icons"]
files = []
for item in INCLUDE:
    p = os.path.join(ROOT, item)
    if os.path.isdir(p):
        for d, _, fs in os.walk(p):
            for f in sorted(fs):
                if f.startswith('.') or f.endswith(('.py', '.md', '.txt')) or f == 'LICENSE':
                    continue
                files.append(os.path.relpath(os.path.join(d, f), ROOT).replace(os.sep, '/'))
    elif os.path.exists(p):
        files.append(item)
if "js/version.js" not in files:
    files.append("js/version.js")
files.sort()
h = hashlib.sha256()
for f in files:
    if f == "js/version.js":          # written below from this hash, so it can't be part of it
        continue
    h.update(f.encode())
    with open(os.path.join(ROOT, f), 'rb') as fh:
        h.update(fh.read())
version = h.hexdigest()[:10]
with open(os.path.join(ROOT, "js", "version.js"), "w") as f:
    f.write(f"// Generated by tools/build_sw.py: the version shown in the menu (same as the offline cache).\nexport const VERSION = '{version[:7]}';\n")
urls = ["./"] + files
sw = f"""// Generated by tools/build_sw.py - offline cache for Slagalica Gusinje.
const VERSION = '{version}';
const CACHE = 'slagalica-' + VERSION;
const FILES = {json.dumps(urls, indent=0)};

// cache: 'reload' - always from the server: the browser's own cache can still hold the previous
// version's files for a few minutes after an update (GitHub Pages lets it keep them 10 minutes)
self.addEventListener('install', e => {{
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(u => new Request(u, {{ cache: 'reload' }}))))
    .then(() => self.skipWaiting()));
}});
self.addEventListener('activate', e => {{
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('slagalica-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});
self.addEventListener('fetch', e => {{
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, {{ ignoreSearch: true }}).then(hit => hit || fetch(req).then(res => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }}
    return res;
  }})));
}});
"""
with open(os.path.join(ROOT, "sw.js"), "w") as f:
    f.write(sw)
print(f"sw.js: {len(urls)} files, version {version}")
